// 山行小日子：登山畫面的光線設定（只有這一份）
// 美術圖本來就畫成「右上方來的暖金色陽光」，這裡的設定只是讓登山客、寵物、路旁東西跟場景站在同一片陽光裡，不改美術方向。
// 太陽在天空的位置、太陽顏色、時間天氣的整體調色（multiply）寫在 trail.js 的 buildPalettes（PAL 表），這裡不重寫，只放「新加的」光線參數。
// 時間的名字跟 PAL 一樣：dawn 清晨、day 白天、sunset 夕陽、dusk 黃昏、night 晚上；白天爬到高處會從 day 慢慢混到 sunset，兩邊的值照比例混。
// 每一個值都要被 trail.js 或 gl2d.js 用到（check 會檢查 trail.js 用到的 LOOK.xxx 這裡都有，光線參數不准寫在別的檔案）
(function(){
'use strict';
const SX = window.SX = window.SX || {};
SX.look = {
  // 整體調色多加的飽和度、對比（1＝不變）：WebGL 併在同一次全螢幕調色裡做，Canvas 2D 用兩三層合成模式蓋上去（不逐點讀像素）
  // 霧天另外一組（照霧的有無直接換，跟天氣一樣）
  grade: {
    dawn:   { sat:1.03, con:1.03 },
    day:    { sat:1.06, con:1.05 },
    sunset: { sat:1.10, con:1.07 },
    dusk:   { sat:1.02, con:1.06 },
    night:  { sat:0.88, con:1.02 },
    fog:    { sat:0.84, con:0.92 }
  },
  // 逆光：太陽在前方天空，登山客、寵物、隊友是背對太陽的，身上整體壓暗一點、往偏藍紫的顏色混一點
  back: { dawn:0.12, day:0.14, sunset:0.2, dusk:0.18, night:0 },
  backCol: [46, 54, 100],
  // 輪廓光：朝太陽那一側的邊緣一圈金色（晚上一定是 0：頭燈照不到自己身上，身上不准發光）
  rim: { dawn:0.55, day:0.5, sunset:0.8, dusk:0.65, night:0 },
  rimCol: [255, 204, 124],
  rimW: 0.018,       // 輪廓光多寬：這一格圖高的幾分之一（約 3 個畫面像素）；背光那邊也這麼寬是空的（登山杖這種細的）就不上光
  liteRes: 1,        // 光線貼圖（剪影、輪廓光）做成原圖的幾倍大：登山客的圖本來就小（一格約 72×187），畫面上已經放大快兩倍，再縮一半剪影會糊出一圈光暈
  // 影子跟著太陽：太陽在畫面右邊，影子往左；太陽在前方天空（逆光），影子往鏡頭這邊（畫面下方）拉長
  shadow: {
    azK: 1.6,            // 太陽偏離畫面中間多少，影子就往反方向斜多少（放大倍數；1.6 時太陽在 80% 寬的地方影子約斜 30 度）
    hi: 0.11, lo: 0.32,  // 太陽在畫面高度 hi（白天）影子最短、lo（快下山）最長
    len: [0.45, 1.1],    // 影子長度（物體高度的幾倍）：太陽最高 → 最低
    castA: 0.5,          // 投影最深的地方多不透明（投影另外一張圖 CAST；腳印、接觸陰影照舊）
    flat: 0.36,          // 地上的影子壓扁多少（從後上方斜看地面）
    cast: { dawn:0.85, day:1, sunset:1, dusk:0.75, night:0.35 },   // 投影（不是接觸陰影）多深，再乘上太陽看得到多少（陰天、雨天變淡）
    hero: 1.3,           // 登山客腳下的影子比一般深這麼多倍
    step: 0.08           // 影子方向、長度每變這麼多才重做一次路旁東西的合成影子（不是每格重做）
  },
  // 森林裡地上的光斑走到登山客身上：只亮在人身上（用剪影當遮罩），跟著往前走從頭滑到腳
  dapple: { a:0.42, col:[255, 230, 156], span:0.9 },   // 最亮多少、顏色、從碰到光斑到離開走幾公尺
  // 自動畫質每一級開不開（跟 trail.js 的 QUAL 一樣六級，0 最好）
  q: {
    rim:     [1, 1, 1, 1, 1, 0],   // 逆光、輪廓光
    dapple:  [1, 1, 1, 1, 0, 0],   // 人身上的光斑（地上的光斑第 4 級起也不畫）
    grade2d: [1, 1, 1, 0, 0, 0]    // Canvas 2D 才看這個：飽和度、對比那幾層（WebGL 是同一次全螢幕調色，不另外花）
  }
};
})();
